import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../app/src-tauri/src/game_art/retail.rs", import.meta.url));
const dats = "https://raw.githubusercontent.com/libretro/libretro-database/master/metadat/no-intro/";

// Game Boy entries carry no game code, so they go by the version's name in each language.
const byName = (generation, versions) => ({ generation, match: (name) => new RegExp(`\\b(${versions})\\b`).test(name) });
const bySerial = (generation, codes) => ({ generation, match: (_, serial) => codes.includes(serial?.slice(0, 3)) });

const systems = [
  {
    dat: "Nintendo - Game Boy",
    generations: [byName(1, "Red|Blue|Yellow|Rote|Blaue|Gelbe|Roja|Azul|Amarilla|Rouge|Bleue|Jaune|Rossa|Blu|Gialla|Aka|Midori|Ao|Pikachu")],
  },
  {
    dat: "Nintendo - Game Boy Color",
    generations: [
      byName(2, "Gold|Silver|Crystal|Goldene|Silberne|Kristall|Oro|Plata|Cristal|Or|Argent|Argento|Cristallo|Kin|Gin|Geum|Eun"),
    ],
  },
  { dat: "Nintendo - Game Boy Advance", generations: [bySerial(3, ["AXV", "AXP", "BPE", "BPR", "BPG"])] },
  {
    dat: "Nintendo - Nintendo DS",
    generations: [bySerial(4, ["ADA", "APA", "CPU", "IPK", "IPG"]), bySerial(5, ["IRB", "IRA", "IRE", "IRD"])],
  },
];

// The Game Boy Color dat lists Taiwanese bootlegs under the main series' names, some untagged.
const mainSeries = /^(Pokemon - |Pocket Monsters[ -])/;
const excluded = /Taiwan|Hong Kong|Pirate|Debug|Proto|Beta|Demo|Kiosk|Distribution|Video|Save Data|Program/;

const roms = [];
for (const { dat, generations } of systems) {
  const response = await fetch(`${dats}${encodeURIComponent(dat)}.dat`);
  if (!response.ok) throw new Error(`${dat}: ${response.status}`);
  for (const [, name, body] of (await response.text()).matchAll(/game \(\n\tname "([^"]*)"(.*?)\n\)/gs)) {
    if (!mainSeries.test(name) || excluded.test(name)) continue;
    const serial = body.match(/serial "([^"]*)"/)?.[1];
    const generation = generations.find(({ match }) => match(name, serial))?.generation;
    if (!generation) continue;
    for (const [, sha1] of body.matchAll(/sha1 ([0-9A-F]{40})/g)) roms.push({ sha1: sha1.toLowerCase(), generation, name });
  }
}
roms.sort((a, b) => a.sha1.localeCompare(b.sha1));

const lines = roms.map(({ sha1, generation, name }) => `    ("${sha1}", ${generation}), // ${name}`);
writeFileSync(
  out,
  `// Generated by scripts/retail-roms.mjs from No-Intro's dats in libretro-database.
pub const ROMS: &[(&str, u8)] = &[
${lines.join("\n")}
];
`,
);
console.log(`${roms.length} retail ROMs`);
