const NONE = "\uffff";
const TERMINATOR = 0xffff;

function character(unit: number) {
  const char = unit < INTL.length ? INTL[unit] : (KOREAN[unit - KOREAN_START] ?? NONE);
  if (char === MALE_HALF_WIDTH_GEN5) return "♂";
  if (char === FEMALE_HALF_WIDTH_GEN5) return "♀";
  return char;
}

function unit(char: string) {
  const intl = char === NONE ? -1 : INTL.indexOf(char);
  if (intl >= 0) return intl;
  const korean = char === NONE ? -1 : KOREAN.indexOf(char);
  if (korean >= 0) return KOREAN_START + korean;
  throw new Error(`"${char}" has no Gen 4 value`);
}

function decode(input: Uint8Array) {
  const data = view(input);
  let decoded = "";
  for (let at = 0; at + 1 < input.length; at += 2) {
    const value = data.getUint16(at, true);
    if (value === TERMINATOR || value === 0) break;
    decoded += character(value);
  }
  return decoded;
}

export const textGen4: Transform<string, Record<string, never>> = {
  kind: "transform",
  decode,
  encode(value, _, previous) {
    // Text the bytes already hold keeps them, since a table can read two values as one character.
    if (decode(previous) === value) return previous.slice();
    if (value.length * 2 > previous.length) throw new Error(`"${value}" is longer than ${previous.length / 2} characters`);
    const encoded = new Uint8Array(previous.length);
    const data = view(encoded);
    const half = halfWidth(value);
    for (let i = 0; i < value.length; i++) {
      const char = value[i];
      const glyph = half && char === "♂" ? MALE_HALF_WIDTH_GEN5 : half && char === "♀" ? FEMALE_HALF_WIDTH_GEN5 : char;
      data.setUint16(i * 2, unit(glyph), true);
    }
    if (value.length * 2 + 1 < encoded.length) data.setUint16(value.length * 2, TERMINATOR, true);
    return encoded;
  },
};
